def _clean(xs, n: int) -> list[str]:
    seen, out = set(), []
    for x in xs or []:
        x = re.sub(r"\s+", " ", str(x or "")).strip()
        if x and x.casefold() not in seen:
            seen.add(x.casefold())
            out.append(x)
    return out[:n]


def social_plan(song: dict) -> list[dict]:
    """この曲の SNS 投稿の予定（post_social.py が作った plan.json から。無ければ空）"""
    posts = []
    root = OUT / "social"
    if not root.exists():
        return posts
    for p in sorted(root.rglob("plan.json")):
        try:
            plan = read_json(p)
        except (OSError, ValueError):
            continue
        mine = plan.get("song") == song["key"] or (p.parent.name == song["slug"] and p.parent.parent.name == song["week"])
        if not mine:
            continue
        for x in plan.get("posts", []):
            if x.get("platform") and x.get("scheduled_at"):
                posts.append({"platform": x["platform"], "date": str(x["scheduled_at"])[:10]})
    return posts


PLATFORM_EN = {"youtube": "YouTube Shorts", "instagram": "Instagram Reels", "tiktok": "TikTok"}


def marketing_en(posts: list[dict]) -> str:
    if not posts:
        return ""
    plats = _clean([PLATFORM_EN.get(p["platform"], p["platform"]) for p in posts], 5)
    days = sorted({p["date"] for p in posts})
    names = plats[0] if len(plats) == 1 else ", ".join(plats[:-1]) + " and " + plats[-1]
    when = f"on {days[0]}" if len(days) == 1 else f"from {days[0]} to {days[-1]}"
    return f"Short videos are scheduled on {names} {when} ({len(posts)} posts)."


def facts(song: dict) -> dict:
    """ピッチの材料（自分たちの記録だけ）"""
    a = load_artist(song["slug"], song.get("label_slug"), missing_ok=True) or {}
    st = _songs.state(song)
    sound, prof, dist = a.get("sound") or {}, a.get("profile") or {}, a.get("distribution") or {}
    act = (a.get("life") or {}).get("act") or {}
    ep = song.get("episode") or {}
    scene = song.get("scene") if isinstance(song.get("scene"), dict) else {}
    posts = social_plan(song)
    lang = str(song.get("language") or "").strip()
    return {
        "artist": song["artist"], "title": song["title"], "release_date": str(st.get("release_date") or "")[:10],
        "genres": _clean(list(song.get("genre") or []) + list(sound.get("genres") or []), 3),
        "style_prompt": song.get("style", ""), "sound_tags": _clean(sound.get("dna_tags"), 8), "bpm": song.get("bpm") or "",
        "instrumental": bool(song.get("instrumental")), "language": LANG_EN.get(lang.lower(), lang),
        "story_en": ep.get("story_en", ""), "theme_ja": ep.get("theme", ""), "scene": scene.get("name") or scene.get("label") or "",
        "bio_en": dist.get("bio_en", ""), "home_ja": act.get("base_now") or prof.get("hometown") or "",
        "posts": posts, "marketing_en": marketing_en(posts), "s4a_claimed": dist.get("s4a_claimed"),
    }


def _pick(table: list[tuple[str, str]], text: str, n: int) -> list[str]:
    return [name for name, pat in table if re.search(pat, text, re.I)][:n]


def _fit(text: str, limit: int = MAX_DESC) -> str:
    """上限に収める：文の切れ目で切る（切れ目が無ければ語の切れ目）"""
    text = re.sub(r"\s+", " ", str(text or "")).strip()
    if len(text) <= limit:
        return text
    cut = text[:limit]
    m = max(cut.rfind(". "), cut.rfind("! "), cut.rfind("? "))
    if m >= limit * 0.5:
        return cut[:m + 1]
    return cut[:cut.rfind(" ")].rstrip(",;:") + "." if " " in cut else cut


def _sentences(text: str, n: int) -> str:
    parts = re.split(r"(?<=[.!?])\s+", re.sub(r"\s+", " ", str(text or "")).strip())
    return " ".join(p for p in parts[:n] if p)


def template_en(f: dict, instruments: list[str], moods: list[str]) -> str:
    """Claude を使わない紹介文（同じ材料から、決まった形で）。入るだけ入れて 500 字に収める"""
    g = f["genres"][0].lower() if f["genres"] else "song"
    bpm = f"{f['bpm']} BPM " if str(f["bpm"]).strip() else ""
    kind = "instrumental " if f["instrumental"] else ""
    head = f"\"{f['title']}\" is a {bpm}{kind}{g} track by {f['artist']}."
    how = ", ".join(i.lower() for i in instruments[:3])
    mood = " and ".join(m.lower() for m in moods)
    feel = (f" It is {mood}, carried by {how}." if mood and how else f" It is {mood}." if mood
            else f" It is carried by {how}." if how else "")
    tail = (" " + f["marketing_en"]) if f["marketing_en"] else ""
    rel = f" Out {f['release_date']}." if f["release_date"] else ""
    room = MAX_DESC - len(head) - len(feel) - len(tail) - len(rel) - 1
    story = ""
    for k in (2, 1):   # エピソードは入る分だけ（2 文 → 1 文 → なし）
        s = _sentences(f["story_en"], k)
        if s and len(s) <= room:
            story = " " + s
            break
    return _fit(head + feel + story + rel + tail)


def _bad(text: str) -> str:
    m = BANNED.search(text or "")
    return m.group(0) if m else ""


def write_with_claude(f: dict) -> tuple[dict | None, str]:
    """Claude に下書きを書いてもらう。500 字を超えたら 1 回だけ書き直してもらう。だめなら None"""
    import _claude
    if not _claude.available():
        return None, "Claude の鍵が無い"
    send = {k: v for k, v in f.items() if k not in ("s4a_claimed", "posts")}
    user = "Facts (JSON):\n" + json.dumps(send, ensure_ascii=False, indent=1)
    res, st = _claude.call_json(SYSTEM, user, SCHEMA, effort="low", max_tokens=4000)
    for _ in range(1):
        if not res:
            return None, st
        d = re.sub(r"\s+", " ", str(res.get("description_en", ""))).strip()
        why = (f"it is {len(d)} characters; the limit is 480" if len(d) > MAX_DESC else
               f"it contains \"{_bad(d)}\", which is not allowed" if _bad(d) else "")
        if not why:
            break
        res, st = _claude.call_json(SYSTEM, user + f"\n\nYour previous description_en was rejected: {why}. Write it again within the rules.",
                                    SCHEMA, effort="low", max_tokens=4000)
    if not res:
        return None, st
    d = re.sub(r"\s+", " ", str(res.get("description_en", ""))).strip()
    if not d or _bad(d):
        return None, "入れてはいけない言葉が残った" if d else "紹介文が空だった"
    res["description_en"] = _fit(d)
    return res, st


def build(song: dict, use_claude: bool = True, quiet: bool = False) -> dict:
    """ピッチの下書きを作って保存する。{"fields", "description_en", "description_ja", "checks", …}"""
    f = facts(song)
    text = " , ".join([f["style_prompt"], " ".join(f["sound_tags"])])
    instruments = _pick(INSTRUMENTS, text, 5)
    if f["instrumental"]:
        instruments = [i for i in instruments if i != "Vocals"]
    moods = _pick(MOODS, text, 2)
    styles = _clean([t.title() if t.islower() else t for t in f["sound_tags"] if t.casefold() not in {g.casefold() for g in f["genres"]}], 3)
    desc_en, desc_ja, by, home_en, cultures = "", "", "決まった形（Claude なし）", "", []
    checks = []
    if use_claude:
        import _claude
        if _claude.available():
            if not quiet:
                step(f"Claude がピッチの下書きを書いています：{f['artist']}「{f['title']}」（1 曲 数円）")
            res, st = write_with_claude(f)
            if res:
                desc_en, desc_ja, by = res["description_en"], str(res.get("description_ja", "")).strip(), "Claude"
                home_en = str(res.get("home_en", "")).strip()
                cultures = _clean(res.get("cultures"), 2)
                moods = _clean(res.get("moods"), 2) or moods
                styles = _clean(res.get("styles"), 3) or styles
                instruments = _clean(res.get("instruments"), 5) or instruments
                if f["instrumental"]:
                    instruments = [i for i in instruments if i.casefold() != "vocals"]
            else:
                checks.append(f"Claude では作れなかったので、決まった形で作りました（{st}）")
        else:
            checks.append("Claude の鍵が無いので、決まった形で作りました（日本語の訳はありません）")
    if not desc_en:
        desc_en = template_en(f, instruments, moods)
    if not f["posts"]:
        checks.append("SNS の投稿の予定がまだ無いので、宣伝の予定は紹介文に入っていません（予定ができたら「下書きを作り直す」）")
    if not f["story_en"]:
        checks.append("この曲のエピソード（英語）が無いので、曲の背景は短くなっています")
    if not f["genres"]:
        checks.append("ジャンルが空です。DistroKid に登録したジャンルを選んでください")
    if f["s4a_claimed"] is not True:
        checks.append("Spotify for Artists をまだ使えるようにしていない組は、先に利用の申請が要ります（下の案内）")
    fields = {
        "genres": f["genres"], "cultures": cultures, "moods": moods, "styles": styles, "instruments": instruments,
        "song_type": "オリジナル（カバーでもリミックスでもない）", "instrumental": "はい（歌なし）" if f["instrumental"] else "いいえ（歌あり）",
        "language": f["language"], "home": home_en or f["home_ja"], "home_ja": f["home_ja"],
    }
    out = {"id": song["id"], "artist": f["artist"], "title": f["title"], "release_date": f["release_date"], "fields": fields,
           "description_en": desc_en, "description_ja": desc_ja, "chars": len(desc_en), "checks": checks, "by": by,
           "text_version": TEXT_VERSION, "at": datetime.now().isoformat(timespec="seconds")}
    assert len(out["description_en"]) <= MAX_DESC
    write_json(draft_path(song), out)
    (draft_dir(song) / "ピッチ.md").write_text(markdown(out), encoding="utf-8")
    if not quiet:
        print(f"   ○ ピッチの下書き：out/publish/{song['key']}/ピッチ.md（紹介文 {len(desc_en)} 字・{by}）")
    return out


