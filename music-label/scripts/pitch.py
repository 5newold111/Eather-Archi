# 記録
def mark(song: dict, what: str) -> str:
    """what：done・skip・undo。結果の一文"""
    st = _songs.state(song)
    p = dict(st.get("pitch") or {})
    today = date.today().isoformat()
    name = f"{song['artist']}「{song['title']}」"
    if what == "done":
        p.pop("skipped_at", None)
        p.update({"done_at": today, "text_version": (load_draft(song) or {}).get("text_version", TEXT_VERSION)})
        msg = f"{name} を「ピッチした」と記録しました"
    elif what == "skip":
        p.pop("done_at", None)
        p["skipped_at"] = today
        msg = f"{name} のピッチは見送りにしました"
    else:
        p = {}
        msg = f"{name} のピッチの記録を取り消しました"
    if p:
        st["pitch"] = p
    else:
        st.pop("pitch", None)
    _songs.save_state(song, st)
    return msg


def auto(quiet: bool = False) -> int:
    """登録したばかりで、まだ下書きが無い曲の下書きを作る（締め切り前の曲だけ）。作った数"""
    n = 0
    for s in _songs.all_songs():
        i = info(s)
        if not i or i["state"] not in ("todo", "soon"):
            continue
        d = load_draft(s)
        if d and d.get("text_version") == TEXT_VERSION:
            continue
        try:
            build(s, quiet=quiet)
            n += 1
        except Exception as e:  # noqa: BLE001  1 曲でつまずいても、ほかの曲は作る
            print(f"   ✕ {s['artist']}「{s['title']}」のピッチの下書きを作れませんでした：{e}")
    return n


