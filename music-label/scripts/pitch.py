def _row_html(i: dict) -> list:
    import _ui
    left = ("—" if i["state"] in ("done", "skip") else f"{-i['days_left']} 日過ぎた" if i["days_left"] < 0
            else "きょう" if i["days_left"] == 0 else f"あと {i['days_left']} 日")
    return [f'<a href="/pitch?id={E(i["id"])}">{E(i["artist"])}「{E(i["title"])}」</a>', E(i["release_date"]), E(i["deadline"]), E(left),
            _ui.badge(STATE_BADGE[i["state"]], i["state_ja"]), "あり" if i["has_draft"] else "まだ"]


