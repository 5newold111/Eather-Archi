def _val(v) -> str:
    return "、".join(v) if isinstance(v, list) else str(v or "")


def markdown(d: dict) -> str:
    lines = [f"# Spotify へのピッチ：{d['artist']}「{d['title']}」", "",
             f"- 配信日：{d['release_date']}（ピッチの締め切りはその 7 日前）",
             f"- 下書き：{d['at']}（{d['by']}）", "",
             "## 画面で選ぶもの（選択肢の名前は少し違うことがあります。近いものを選ぶ）", ""]
    lines += [f"- {name}：{_val(d['fields'].get(k)) or '（なし）'}" for k, name in FIELD_ROWS]
    lines += ["", f"## 曲の紹介文（英語・{d['chars']} 字／上限 {MAX_DESC} 字）", "", d["description_en"], ""]
    if d.get("description_ja"):
        lines += ["## 日本語の訳（読む用。Spotify には入れない）", "", d["description_ja"], ""]
    if d.get("checks"):
        lines += ["## 確かめること", ""] + [f"- {c}" for c in d["checks"]] + [""]
    return "\n".join(lines)


def load_draft(song: dict) -> dict | None:
    p = draft_path(song)
    try:
        return read_json(p) if p.exists() else None
    except (OSError, ValueError):
        return None


