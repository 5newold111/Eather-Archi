"""
Spotify の編集部への推薦（ピッチ）を、配信の 7 日前までに出せるように用意する（決定 171）

  ピッチとは：Spotify for Artists（アーティスト用の管理画面）から、まだ配信されていない 1 曲を
              Spotify の編集部（公式プレイリストを作る人たち）に推薦すること。配信日の 7 日前までに出す必要がある。
              出しておくと、配信の日にフォロワーの Release Radar（新曲のおすすめ）にも載る。

  ここがすること
    ・DistroKid に登録済みで、まだ配信されていない曲を「ピッチが要る曲」として並べる（締め切り＝配信日の 7 日前）
    ・ピッチの画面で選ぶもの（ジャンル・ムード・スタイル・楽器・曲の種類・言語・出身地）と、曲の紹介文（英語・500 字まで）を下書きする
      紹介文は Claude が書く（1 曲 数円）。鍵が無いとき・--no-claude のときは、同じ材料から決まった形で作る（0 円）
    ・下書きを out/publish/<曲>/ピッチ.md に残す（公開セットと同じ場所）
    ・「ピッチした」「見送る」を曲の記録に残す
  ここがしないこと
    ・Spotify for Artists の画面には入力しない・送信しない（貼るのと送信は Gon さん）
    ・紹介文に、事実でないこと（取材・プレイリスト入り・再生数など）は書かない。「AI」という言葉も入れない
      （AI の申告は DistroKid の登録で済んでいる。決定 61。ピッチの画面で聞かれたら、正直に答える）

  状態：todo（出せる）・soon（締め切りまで 3 日以内）・late（締め切りを過ぎた。もう出せない）・done（出した）・skip（見送り）

使い方
  python3 scripts/pitch.py todos                  # ピッチが要る曲の一覧（締め切りの近い順）
  python3 scripts/pitch.py build <曲 ID>          # 下書きを作る（作り直す）。--no-claude で Claude を使わない
  python3 scripts/pitch.py done <曲 ID>           # ピッチした
  python3 scripts/pitch.py skip <曲 ID>           # この曲は見送る
  python3 scripts/pitch.py undo <曲 ID>           # 「ピッチした」「見送る」を取り消す
  python3 scripts/pitch.py auto                   # 登録したばかりの曲の下書きを作る（定期実行から。どこにも送らない）
"""
