def _d(x) -> date | None:
    try:
        return date.fromisoformat(str(x)[:10]) if x else None
    except ValueError:
        return None


def info(song: dict, today: date | None = None) -> dict | None:
    """その曲のピッチの状態。ピッチの対象でなければ None（登録済み・未配信・配信日が分かる曲だけ）"""
    st = _songs.state(song)
    if st.get("status") != "registered":
        return None
    rel = _d(st.get("release_date"))
    if rel is None:
        return None
    today = today or date.today()
    deadline = rel - timedelta(days=PITCH_DAYS)
    left = (deadline - today).days
    p = st.get("pitch") or {}
    if p.get("done_at"):
        state = "done"
    elif p.get("skipped_at"):
        state = "skip"
    elif left < 0:
        state = "late"
    elif left <= SOON_DAYS:
        state = "soon"
    else:
        state = "todo"
    return {"id": song["id"], "key": song["key"], "slug": song["slug"], "artist": song["artist"], "title": song["title"],
            "release_date": rel.isoformat(), "deadline": deadline.isoformat(), "days_left": left, "state": state,
            "state_ja": STATE_JA[state], "registered_at": st.get("registered_at", ""), "has_draft": draft_path(song).exists(),
            "done_at": p.get("done_at", ""), "skipped_at": p.get("skipped_at", "")}


def all_info(today: date | None = None) -> list[dict]:
    out = [i for s in _songs.all_songs() if (i := info(s, today))]
    order = {"soon": 0, "todo": 1, "late": 2, "done": 3, "skip": 4}
    return sorted(out, key=lambda i: (order[i["state"]], i["days_left"], i["artist"]))


def todos(today: date | None = None) -> list[dict]:
    """ダッシュボードの「あなたの番」に出す：まだピッチしていない曲（締め切りの近い順）。過ぎた曲は 7 日だけ知らせる"""
    out = []
    for i in all_info(today):
        if i["state"] in ("todo", "soon") or (i["state"] == "late" and i["days_left"] >= -PITCH_DAYS):
            what = (f"締め切りを {-i['days_left']} 日過ぎました（もう出せません。「見送る」で消せます）" if i["state"] == "late"
                    else "きょうが締め切り" if i["days_left"] == 0 else f"あと {i['days_left']} 日")
            out.append({**{k: i[k] for k in ("id", "artist", "title", "release_date", "deadline", "days_left", "state")},
                        "what": f"Spotify にピッチする（{i['deadline']} まで・{what}）",
                        "action": {"kind": "link", "label": "ピッチの下書きを開く", "href": f"/pitch?id={i['id']}"}})
    return out


def status(today: date | None = None) -> dict:
    """軽いまとめ（ダッシュボードの上の数字・知らせ用）"""
    xs = all_info(today)
    n = lambda s: sum(1 for i in xs if i["state"] == s)  # noqa: E731
    return {"open": n("todo") + n("soon"), "soon": n("soon"), "late": sum(1 for i in xs if i["state"] == "late" and i["days_left"] >= -PITCH_DAYS),
            "done": n("done")}


def alerts(today: date | None = None) -> list[str]:
    """締め切りが近い曲の知らせ（スマホへの通知などに使う一文）"""
    return [f"Spotify のピッチ：{i['artist']}「{i['title']}」は {i['deadline']} まで（あと {i['days_left']} 日）"
            for i in all_info(today) if i["state"] == "soon"]


