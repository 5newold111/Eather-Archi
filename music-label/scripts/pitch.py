def _song_or_exit(song_id: str) -> dict:
    song = _songs.by_id(song_id)
    if song is None:
        print(f"   ✕ 曲が見つかりません：{song_id}")
        print("【結果】曲が見つかりませんでした")
        sys.exit(1)
    return song


def main() -> None:
    ap = argparse.ArgumentParser(description="Spotify の編集部への推薦（ピッチ）の下書きと記録（決定 171）")
    sub = ap.add_subparsers(dest="cmd", required=True)
    b = sub.add_parser("build", help="下書きを作る（作り直す）")
    b.add_argument("id")
    b.add_argument("--no-claude", action="store_true", help="Claude を使わず、決まった形で作る（0 円）")
    for name, h in (("done", "ピッチした"), ("skip", "この曲は見送る"), ("undo", "記録を取り消す")):
        sub.add_parser(name, help=h).add_argument("id")
    sub.add_parser("todos", help="ピッチが要る曲の一覧")
    sub.add_parser("auto", help="登録したばかりの曲の下書きを作る（定期実行）").add_argument("--quiet", action="store_true")
    a = ap.parse_args()
    if a.cmd == "build":
        song = _song_or_exit(a.id)
        d = build(song, use_claude=not a.no_claude)
        for c in d["checks"]:
            print(f"   ・{c}")
        print(f"【結果】ピッチの下書きを作りました（紹介文 {d['chars']} 字・{d['by']}）")
    elif a.cmd in ("done", "skip", "undo"):
        song = _song_or_exit(a.id)
        if a.cmd != "undo" and info(song) is None:
            print("   ✕ この曲はピッチの対象ではありません（DistroKid に登録済みで、まだ配信されていない曲だけ）")
            print("【結果】記録しませんでした（ピッチの対象ではない曲）")
            sys.exit(1)
        msg = mark(song, a.cmd)
        print(f"   ○ {msg}")
        print(f"【結果】{msg}")
    elif a.cmd == "todos":
        xs = todos()
        if not xs:
            print("   ピッチが要る曲はありません")
        for t in xs:
            print(f"   {'！' if t['state'] != 'todo' else '○'} {t['artist']}「{t['title']}」：{t['what']}")
    elif a.cmd == "auto":
        n = auto(quiet=a.quiet)
        if n or not a.quiet:
            print(f"【結果】ピッチの下書きを {n} 曲ぶん作りました" if n else "【結果】新しく作る下書きはありませんでした")


if __name__ == "__main__":
    main()
